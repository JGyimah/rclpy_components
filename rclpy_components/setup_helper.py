"""
Registration of rclpy components from a package's ``setup.py``.

This is the counterpart to ``rclcpp_components_register_nodes()`` in CMake. A
plugin package calls :func:`register_nodes` and splices the result into its
``data_files``, which installs a resource index entry the container then reads:

    from rclpy_components.setup_helper import register_nodes

    setup(
        name=package_name,
        data_files=[
            ("share/ament_index/resource_index/packages", ["resource/" + package_name]),
            ("share/" + package_name, ["package.xml"]),
            *register_nodes(package_name, {
                "featx_plugin::Boot": "py_plugin_executor.boot:Boot",
            }),
        ],
        ...
    )

The generated file is written beside ``setup.py`` in a dot-directory, which
belongs in the package's ``.gitignore``.
"""

import os

from . import RESOURCE_GROUP

#: Where the generated resource file is staged before installation.
STAGING_DIR = '.rclpy_components'


def register_nodes(package: str, components: dict[str, str], *, directory: str = '') -> list:
    """
    Declare the components a package provides.

    ``components`` maps the name a component is loaded by to the import target
    that provides it, written ``module:Class``. The return value is a list of
    ``data_files`` entries to splice into ``setup()``.
    """
    if not components:
        return []

    for name, target in components.items():
        if ':' not in target:
            raise ValueError(
                f'component {name!r} has target {target!r}; '
                f"write it as 'module:Class'"
            )

    # setup.py runs with the package root as the working directory, so a
    # relative path stages the file beside it.
    staging = os.path.join(directory, STAGING_DIR) if directory else STAGING_DIR
    os.makedirs(staging, exist_ok=True)

    path = os.path.join(staging, package)
    with open(path, 'w') as f:
        f.write(
            '# Generated by rclpy_components.setup_helper.register_nodes.\n'
            '# Each line is: <component name>;<module>:<Class>\n'
        )
        for name in sorted(components):
            f.write(f'{name};{components[name]}\n')

    return [(f'share/ament_index/resource_index/{RESOURCE_GROUP}', [path])]
